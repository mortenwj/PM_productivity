def main() -> int:
    rows: list[dict] = []
    for wid, wt, st, chg, par, title, scd, res, clo in SPEC:
        f: dict = {
            "System.Id": wid,
            "System.WorkItemType": wt,
            "System.State": st,
            "System.ChangedDate": chg,
            "System.Title": title,
            "Microsoft.VSTS.Common.StateChangeDate": scd,
        }
        if par is not None:
            f["System.Parent"] = par
        if res:
            f["Microsoft.VSTS.Common.ResolvedDate"] = res
        if clo:
            f["Microsoft.VSTS.Common.ClosedDate"] = clo
        rows.append(
            {
                "id": wid,
                "fields": f,
                "multilineFieldsFormat": {},
                "url": f"https://tieto-si.visualstudio.com/_apis/wit/workItems/{wid}",
            }
        )
    out = TOOLS / "pilot_weekly_bugs_batch.json"
    out.write_text(json.dumps(rows, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(out, len(rows))
    return 0


